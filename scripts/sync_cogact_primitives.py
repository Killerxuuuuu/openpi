"""Vendor the dependency-closed numerical primitives from the local CogACT source.

Run from any directory; the resulting module has no dependency on a sibling
checkout or on CogACT/Prismatic model packages. Function bodies are unchanged.
"""

import argparse
import ast
import hashlib
from pathlib import Path

ROOTS = {
    "QuantVLAConfig",
    "PTQLinear",
    "apply_atm_calibration",
    "apply_ohb_calibration",
    "apply_lvc_affine_calibration",
    "apply_lvc_dense_calibration",
    "apply_physical_sensitivity_mixed_precision",
    "_compute_logits_std_per_head",
    "_compute_rms_scalar",
    "_build_physical_channel_weights",
    "clone_batch_to_cpu",
}


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=root.parent / "DA-PTQ/vla/quantvla_ptq.py")
    args = parser.parse_args()
    raw = args.source.read_bytes()
    source = raw.decode("utf-8-sig")
    tree = ast.parse(source)
    # The reference contains a few repeated definitions; Python uses the last.
    definitions = {node.name: node for node in tree.body if isinstance(node, ast.FunctionDef | ast.ClassDef)}
    selected = set(ROOTS)
    pending = list(ROOTS)
    while pending:
        node = definitions[pending.pop()]
        for dependency in {item.id for item in ast.walk(node) if isinstance(item, ast.Name)} & definitions.keys():
            if dependency not in selected:
                selected.add(dependency)
                pending.append(dependency)
    lines = source.splitlines()
    imports = "\n".join(
        ast.get_source_segment(source, node) for node in tree.body if isinstance(node, ast.Import | ast.ImportFrom)
    )
    chunks = []
    for node in sorted((definitions[name] for name in selected), key=lambda item: item.lineno):
        start = min([node.lineno, *[item.lineno for item in node.decorator_list]])
        chunks.append("\n".join(lines[start - 1 : node.end_lineno]))
    digest = hashlib.sha256(raw).hexdigest()
    header = (
        '"""Unmodified numerical definitions vendored from local DA-PTQ CogACT.\n\n'
        "Generated by scripts/sync_cogact_primitives.py; do not edit by hand.\n"
        f"Source SHA256: {digest}\n"
        '"""\n# ruff: noqa -- preserve the reference implementation verbatim\n\n'
    )
    destination = root / "src/openpi/quantization/cogact_primitives.py"
    destination.write_text(
        header + imports + f'\n\nSOURCE_SHA256 = "{digest}"\n\n\n' + "\n\n\n".join(chunks) + "\n", encoding="utf-8"
    )
    print(f"Vendored {len(selected)} definitions into {destination}; SHA256={digest}")
    sampling_source = args.source.parent.parent / "scripts/quantize_quantvla.py"
    sampling_text = sampling_source.read_text(encoding="utf-8-sig")
    sampling_tree = ast.parse(sampling_text)
    names = {
        "_extract_action_xy_from_batch",
        "_build_spatial_edges",
        "_spatial_bin_index",
        "_collect_spatial_balanced_calibration_batches",
    }
    sampling_chunks = [
        ast.get_source_segment(sampling_text, node)
        for node in sampling_tree.body
        if isinstance(node, ast.FunctionDef) and node.name in names
    ]
    sampling_digest = hashlib.sha256(sampling_source.read_bytes()).hexdigest()
    sampling_header = (
        '"""Unmodified action-XY quota sampler from the local CogACT entrypoint."""\n'
        "# ruff: noqa -- preserve reference definitions\n"
        "from __future__ import annotations\n"
        "import math\nfrom collections import defaultdict\n"
        "from typing import Any, Dict, List, Optional, Sequence, Tuple\n"
        "import torch\n"
        "from openpi.quantization.cogact_primitives import clone_batch_to_cpu\n"
        f'SOURCE_SHA256 = "{sampling_digest}"\n\n'
    )
    (destination.parent / "cogact_sampling.py").write_text(
        sampling_header + "\n\n\n".join(sampling_chunks) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
