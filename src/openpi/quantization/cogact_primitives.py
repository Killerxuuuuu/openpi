def _factorize_dense_delta_low_rank(matrix: torch.Tensor, rank: int) -> Tuple[torch.Tensor, torch.Tensor]:
    transform = torch.as_tensor(matrix, dtype=torch.float32)
    if transform.ndim != 2 or transform.shape[0] != transform.shape[1]:
        return torch.empty((0, 0), dtype=torch.float32), torch.empty((0, 0), dtype=torch.float32)

    out_dim = int(transform.shape[0])
    keep_rank = max(0, min(int(rank), out_dim))
    if keep_rank <= 0:
        return torch.empty((out_dim, 0), dtype=torch.float32), torch.empty((out_dim, 0), dtype=torch.float32)

    eye = torch.eye(out_dim, dtype=torch.float32, device=transform.device)
    delta = transform - eye
    if (not bool(torch.isfinite(delta).all())) or float(delta.abs().amax().item()) <= 0.0:
        return torch.empty((out_dim, 0), dtype=torch.float32), torch.empty((out_dim, 0), dtype=torch.float32)

    try:
        u, s, vh = torch.linalg.svd(delta.to(torch.float64), full_matrices=False)
    except Exception:
        return torch.empty((out_dim, 0), dtype=torch.float32), torch.empty((out_dim, 0), dtype=torch.float32)

    r = min(keep_rank, int(s.numel()))
    if r <= 0:
        return torch.empty((out_dim, 0), dtype=torch.float32), torch.empty((out_dim, 0), dtype=torch.float32)

    s_keep = s[:r]
    valid = s_keep > 1e-10
    if not bool(torch.any(valid)):
        return torch.empty((out_dim, 0), dtype=torch.float32), torch.empty((out_dim, 0), dtype=torch.float32)

    u_keep = u[:, :r][:, valid]
    s_keep = s_keep[valid]
    vh_keep = vh[:r, :][valid, :]

    left = (u_keep * s_keep.unsqueeze(0)).to(torch.float32)
    right = vh_keep.transpose(0, 1).to(torch.float32)
    return left, right


