    def _apply_lvc_dense_bypass_(self, output: torch.Tensor) -> torch.Tensor:
        if (
            (not bool(getattr(self, "lvc_dense_bypass_runtime_enable", True)))
            or (not bool(self.lvc_bypass_enabled.item()))
            or output.ndim == 0
            or output.shape[-1] != self.out_features
        ):
            return output

        left = self._buffers.get("lvc_bypass_left", None)
        right = self._buffers.get("lvc_bypass_right", None)
        shift = self._buffers.get("lvc_bypass_shift", None)
        if (not torch.is_tensor(left)) or (not torch.is_tensor(right)) or (not torch.is_tensor(shift)):
            return output

        flat = output.reshape(-1, self.out_features)
        out_dtype = flat.dtype
        if left.ndim != 2 or right.ndim != 2 or left.shape[0] != self.out_features or right.shape[0] != self.out_features:
            return output
        if left.shape[1] != right.shape[1]:
            return output

        rank = int(left.shape[1])
        if rank > 0:
            work_dtype = left.dtype
            if flat.device.type == "cpu" and work_dtype in {torch.float16, torch.bfloat16}:
                work_dtype = torch.float32

            flat_work = flat.to(dtype=work_dtype)
            left_work = left.to(device=flat.device, dtype=work_dtype)
            right_work = right.to(device=flat.device, dtype=work_dtype)
            correction = (flat_work @ left_work) @ right_work.transpose(0, 1)
            flat = flat + correction.to(dtype=out_dtype)

        shift_work = shift.to(device=flat.device, dtype=out_dtype)
        flat = flat + shift_work
        return flat.reshape_as(output)

