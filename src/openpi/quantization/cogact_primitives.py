def _project_block_diagonal(matrix: torch.Tensor, block_size: int) -> torch.Tensor:
    data = torch.as_tensor(matrix, dtype=torch.float32)
    if data.ndim != 2 or data.shape[0] != data.shape[1]:
        return data

    dim = int(data.shape[0])
    blk = max(1, int(block_size))
    if blk >= dim:
        return data

    projected = torch.zeros_like(data)
    for start in range(0, dim, blk):
        end = min(dim, start + blk)
        projected[start:end, start:end] = data[start:end, start:end]
    return projected


def _project_low_rank_identity_delta(matrix: torch.Tensor, rank: int) -> torch.Tensor:
    data = torch.as_tensor(matrix, dtype=torch.float32)
    if data.ndim != 2 or data.shape[0] != data.shape[1]:
        return data

    dim = int(data.shape[0])
    keep_rank = max(0, int(rank))
    eye = torch.eye(dim, dtype=torch.float32)
    if keep_rank <= 0:
        return eye
    if keep_rank >= dim:
        return data

    try:
        delta = (data - eye).to(torch.float64)
        u, s, vh = torch.linalg.svd(delta, full_matrices=False)
        r = min(keep_rank, int(s.numel()))
        if r <= 0:
            return eye
        delta_lr = (u[:, :r] * s[:r].unsqueeze(0)) @ vh[:r, :]
        return (eye.to(torch.float64) + delta_lr).to(torch.float32)
    except Exception:
        return data


def _clip_dense_affine_delta(matrix: torch.Tensor, delta_clip: float) -> torch.Tensor:
    data = torch.as_tensor(matrix, dtype=torch.float32)
    if data.ndim != 2 or data.shape[0] != data.shape[1]:
        return data

    clip_value = max(0.0, float(delta_clip))
    if clip_value <= 0.0:
        return data

    dim = int(data.shape[0])
    eye = torch.eye(dim, dtype=torch.float32)
    delta = (data - eye).clamp(min=-clip_value, max=clip_value)
    return eye + delta


def _solve_weighted_identity_prior_dense_affine(
    quant_cov: torch.Tensor,
    teacher_cov: torch.Tensor,
    anchor_matrix: torch.Tensor,
    weight_vec: torch.Tensor,
    ridge: float,
    feature_lambda: float,
    identity_lambda: float,
    solver_rcond: float,
) -> torch.Tensor:
    q_cov = torch.as_tensor(quant_cov, dtype=torch.float64)
    t_cov = torch.as_tensor(teacher_cov, dtype=torch.float64)
    anchor = torch.as_tensor(anchor_matrix, dtype=torch.float64)
    weights = torch.as_tensor(weight_vec, dtype=torch.float64).flatten()

    dim = int(q_cov.shape[0])
    eye = torch.eye(dim, dtype=torch.float64)
    if weights.numel() != dim:
        weights = torch.ones(dim, dtype=torch.float64)

    row_weights = weights.view(-1, 1)
    q_weighted = q_cov * row_weights
    t_weighted = t_cov * row_weights

    lhs = q_weighted.transpose(0, 1) @ q_weighted
    rhs = q_weighted.transpose(0, 1) @ t_weighted

    ridge_term = max(0.0, float(ridge))
    feature_term = max(0.0, float(feature_lambda))
    identity_term = max(0.0, float(identity_lambda))

    if ridge_term > 0.0:
        lhs = lhs + ridge_term * eye
    if feature_term > 0.0:
        lhs = lhs + feature_term * eye
        rhs = rhs + feature_term * anchor
    if identity_term > 0.0:
        lhs = lhs + identity_term * eye
        rhs = rhs + identity_term * eye

    try:
        solution = torch.linalg.lstsq(lhs, rhs).solution
    except Exception:
        rcond_value = max(1e-8, float(solver_rcond))
        solution = torch.linalg.pinv(lhs, rcond=rcond_value) @ rhs

    if not bool(torch.isfinite(solution).all()):
        rcond_value = max(1e-8, float(solver_rcond))
        solution = torch.linalg.pinv(lhs, rcond=rcond_value) @ rhs

    return solution.to(torch.float32)


def _symmetric_quant_dequant(
    tensor: torch.Tensor,
    num_bits: int,
    clip_abs: Optional[torch.Tensor] = None,
    per_channel: bool = False,
    channel_dim: int = 0,
) -> torch.Tensor:
    if num_bits >= 16 or not torch.is_floating_point(tensor) or tensor.numel() == 0:
        return tensor

    data = tensor.float()
    if clip_abs is None:
        if per_channel and data.ndim > 1:
            reduce_dims = tuple(dim for dim in range(data.ndim) if dim != channel_dim)
            clip_abs = data.detach().abs().amax(dim=reduce_dims, keepdim=True).clamp(min=1e-8)
        else:
            clip_abs = data.detach().abs().amax().clamp(min=1e-8)
    else:
        clip_abs = clip_abs.to(device=data.device, dtype=data.dtype).clamp(min=1e-8)

    qmax = float((1 << (int(num_bits) - 1)) - 1)
    scale = clip_abs / max(qmax, 1.0)
    quant = torch.round((data / scale).clamp(min=-qmax - 1.0, max=qmax)) * scale
    return quant.to(dtype=tensor.dtype)


def _compute_mse_scales_per_outchannel(
    weight_2d: torch.Tensor,
    num_bits: int,
    chunk_rows: int = 256,
) -> torch.Tensor:
    """DuQuant-style tiny-grid MSE scale search, chunked to avoid OOM.

    Args:
        weight_2d: [out_features, in_features] float tensor.
        num_bits: quantization bits.
        chunk_rows: rows per chunk in the MSE search.
    """
    if num_bits >= 16 or weight_2d.numel() == 0:
        return torch.ones(weight_2d.shape[0], device=weight_2d.device, dtype=weight_2d.dtype)

    w = weight_2d.to(torch.float32)
    out_features = w.shape[0]
    qmax = float((1 << (int(num_bits) - 1)) - 1)
    alphas = torch.tensor([0.5, 0.75, 1.0, 1.25, 1.5], device=w.device, dtype=w.dtype)

    best_scales = torch.empty(out_features, device=w.device, dtype=w.dtype)
    step = max(1, int(chunk_rows))

    for start in range(0, out_features, step):
        end = min(start + step, out_features)
        block = w[start:end]  # [C, I]

        max_abs = block.detach().abs().amax(dim=1).clamp(min=1e-8)
        base = max_abs / max(qmax, 1.0)
        scales = (base[:, None] / alphas[None, :]).clamp(min=1e-8)  # [C, 5]

        block_exp = block[:, None, :]  # [C, 1, I]
        scales_exp = scales[:, :, None]  # [C, 5, I]

        quant = torch.round((block_exp / scales_exp).clamp(min=-qmax - 1.0, max=qmax)) * scales_exp
        mse = ((quant - block_exp) ** 2).mean(dim=2)  # [C, 5]
        idx = torch.argmin(mse, dim=1)

        row_ids = torch.arange(end - start, device=w.device)
        best_scales[start:end] = scales[row_ids, idx]

    return best_scales


def _zigzag_permutation(energy: torch.Tensor) -> torch.Tensor:
    order = torch.argsort(energy, descending=True)
    n = int(order.numel())
    if n <= 1:
        return order.to(dtype=torch.long)

    perm = torch.empty(n, dtype=torch.long, device=order.device)
    left, right = 0, n - 1
    for idx in range(n):
        if idx % 2 == 0:
            perm[idx] = order[left]
            left += 1
        else:
            perm[idx] = order[right]
            right -= 1
    return perm


def _svd_orthogonal_basis(
    matrix_2d: torch.Tensor,
    width: int,
    svd_device: Optional[torch.device] = None,
) -> torch.Tensor:
    if width <= 0:
        return torch.zeros((0, 0), dtype=torch.float32)

    device = svd_device or torch.device("cpu")

    def _run_svd(target_device: torch.device) -> torch.Tensor:
        data = matrix_2d.detach().to(device=target_device, dtype=torch.float32)
        u, _, _ = torch.linalg.svd(data, full_matrices=True)
        return u.detach().to(device="cpu", dtype=torch.float32)

    try:
        u = _run_svd(device)
    except Exception:
        if device.type != "cpu":
            try:
                u = _run_svd(torch.device("cpu"))
            except Exception:
                return torch.eye(width, dtype=torch.float32)
        else:
            return torch.eye(width, dtype=torch.float32)

    if u.shape[0] != width:
        return torch.eye(width, dtype=torch.float32)
    if u.shape[1] < width:
        pad = torch.zeros((width, width - u.shape[1]), dtype=u.dtype)
        u = torch.cat([u, pad], dim=1)
    return u[:, :width].to(dtype=torch.float32)


