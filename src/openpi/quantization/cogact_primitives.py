    def set_lvc_dense_bypass_(
        self,
        left: torch.Tensor,
        right: torch.Tensor,
        shift: torch.Tensor,
        bypass_dtype: torch.dtype,
    ) -> bool:
        left_tensor = torch.as_tensor(left, dtype=torch.float32)
        right_tensor = torch.as_tensor(right, dtype=torch.float32)
        shift_tensor = torch.as_tensor(shift, dtype=torch.float32).flatten()

        if shift_tensor.numel() != int(self.out_features):
            return False
        if left_tensor.ndim != 2 or right_tensor.ndim != 2:
            return False
        if left_tensor.shape[0] != int(self.out_features) or right_tensor.shape[0] != int(self.out_features):
            return False
        if left_tensor.shape[1] != right_tensor.shape[1]:
            return False
        if not bool(torch.isfinite(left_tensor).all()) or not bool(torch.isfinite(right_tensor).all()):
            return False
        if not bool(torch.isfinite(shift_tensor).all()):
            return False

        target_dtype = bypass_dtype if bypass_dtype in {torch.float16, torch.bfloat16, torch.float32} else torch.float16
        self._buffers["lvc_bypass_left"] = left_tensor.to(device=self.weight.device, dtype=target_dtype).contiguous()
        self._buffers["lvc_bypass_right"] = right_tensor.to(device=self.weight.device, dtype=target_dtype).contiguous()
        self._buffers["lvc_bypass_shift"] = shift_tensor.to(device=self.weight.device, dtype=torch.float32).contiguous()
        self.lvc_bypass_enabled.fill_(True)
        return True

