    def _keep_master_buffers_on_cpu_(self) -> None:
        # Master copies are only used for occasional requantization; keeping them on CPU
        # avoids duplicating large LLM weights in GPU memory.
        weight_master = self._buffers.get("weight_master", None)
        if torch.is_tensor(weight_master):
            self._buffers["weight_master"] = weight_master.to(device="cpu", dtype=torch.float32)

        bias_master = self._buffers.get("bias_master", None)
        if torch.is_tensor(bias_master):
            self._buffers["bias_master"] = bias_master.to(device="cpu", dtype=torch.float32)

    def _apply(self, fn):
        # Prevent transient GPU spikes: keep master copies out of nn.Module._apply
        # traversal so `.to("cuda")` does not momentarily copy them to GPU.
        weight_master = self._buffers.pop("weight_master", None)
        bias_master = self._buffers.pop("bias_master", None)

        try:
            module = super()._apply(fn)
        finally:
            if torch.is_tensor(weight_master):
                self._buffers["weight_master"] = weight_master.to(device="cpu", dtype=torch.float32)
            elif weight_master is not None:
                self._buffers["weight_master"] = weight_master

            if torch.is_tensor(bias_master):
                self._buffers["bias_master"] = bias_master.to(device="cpu", dtype=torch.float32)
            elif bias_master is not None:
                self._buffers["bias_master"] = bias_master

        self._keep_master_buffers_on_cpu_()
        return module

